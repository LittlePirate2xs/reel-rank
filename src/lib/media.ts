import type { MediaAsset } from "@/types";
import { availableMediaIds } from "@/lib/media-availability";

/* ============================================================================
   Media manifest — the only place media paths are written down.

   Each asset declares the path it lives at under /public. Whether the file is
   actually present is decided by `availableMediaIds`, which is generated by
   `scripts/wire-media.ps1`. Missing files render a designed placeholder frame
   rather than a broken image, so the site never looks unfinished.

   To wire real assets:
     powershell -File scripts\wire-media.ps1
   That copies what it can find and regenerates `lib/media-availability.ts`.
   No component changes are ever needed.
   ========================================================================= */

function asset(
  kind: MediaAsset["kind"],
  id: string,
  src: string,
  alt: string,
  width: number,
  height: number,
  poster = "",
): MediaAsset {
  return {
    id,
    kind,
    src,
    poster,
    alt,
    width,
    height,
    placeholder: !availableMediaIds.has(id),
    playable: false,
  };
}

function image(
  id: string,
  src: string,
  alt: string,
  width: number,
  height: number,
): MediaAsset {
  return asset("image", id, src, alt, width, height);
}

function video(
  id: string,
  src: string,
  posterId: string,
  posterPath: string,
  alt: string,
  width: number,
  height: number,
): MediaAsset {
  // A video is drawn in grids and cards by its POSTER, which is a still. So the
  // poster decides whether there is anything to render, and the video file
  // decides whether there is anything to play. Keeping those separate lets a
  // film look finished in every layout while the player still reports honestly
  // that the moving file has not been wired yet.
  const hasPoster = availableMediaIds.has(posterId);
  return {
    id,
    kind: "video",
    src,
    poster: hasPoster ? posterPath : "",
    alt,
    width,
    height,
    placeholder: !hasPoster,
    playable: availableMediaIds.has(id),
  };
}

